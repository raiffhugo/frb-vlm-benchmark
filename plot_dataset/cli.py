from __future__ import annotations

import argparse
import logging
from pathlib import Path

from plot_dataset.plotter import (
    DEFAULT_IMAGE_DPI,
    DEFAULT_IMAGE_HEIGHT,
    DEFAULT_IMAGE_WIDTH,
    DatasetPlotter,
    PlotConfig,
)
from simulate_dataset.cli import configure_logging


def add_plot_dataset_parser(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--labels",
        type=Path,
        default=Path("dataset/metadata/labels.jsonl"),
        help="labels.jsonl file generated by the simulate_dataset module.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("dataset/images"),
        help="Output directory for the PNG images.",
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("dataset/metadata/image_manifest.jsonl"),
        help="JSONL image manifest file.",
    )
    parser.add_argument(
        "--cmap",
        default="viridis",
        help="Matplotlib colormap.",
    )
    parser.add_argument(
        "--normalization",
        choices=("linear", "minmax", "zscore", "percentile"),
        default="percentile",
        help="Normalization applied before plotting.",
    )
    parser.add_argument(
        "--percentile-low",
        type=float,
        default=1.0,
        help="Lower percentile used with --normalization percentile.",
    )
    parser.add_argument(
        "--percentile-high",
        type=float,
        default=99.0,
        help="Upper percentile used with --normalization percentile.",
    )
    parser.add_argument(
        "--width",
        type=int,
        default=DEFAULT_IMAGE_WIDTH,
        help="Standardized image width in pixels.",
    )
    parser.add_argument(
        "--height",
        type=int,
        default=DEFAULT_IMAGE_HEIGHT,
        help="Standardized image height in pixels.",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=DEFAULT_IMAGE_DPI,
        help="DPI used to convert pixels into figure size.",
    )
    title_group = parser.add_mutually_exclusive_group()
    title_group.add_argument(
        "--include-title",
        action="store_true",
        help="Add an anonymous title to the PNG. The default is no title.",
    )
    title_group.add_argument(
        "--no-title",
        action="store_true",
        help="Kept for compatibility: images are already generated without a title by default.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing PNGs and manifest.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable verbose logging on the console and in the log file.",
    )


def run_plot_dataset(args: argparse.Namespace) -> None:
    labels_path = args.labels.expanduser()
    project_root = labels_path.resolve().parents[2]
    log_file = configure_logging(project_root, verbose=args.verbose)
    logging.getLogger("matplotlib").setLevel(logging.WARNING)

    config = PlotConfig(
        labels_path=labels_path,
        output_dir=args.output_dir.expanduser(),
        manifest_path=args.manifest.expanduser(),
        cmap=args.cmap,
        normalization=args.normalization,
        percentile_low=args.percentile_low,
        percentile_high=args.percentile_high,
        width=args.width,
        height=args.height,
        dpi=args.dpi,
        include_title=args.include_title,
    )
    plotter = DatasetPlotter(config=config, project_root=project_root)
    records = plotter.plot_all(overwrite=args.overwrite)
    logging.getLogger(__name__).info(
        "Plotting finished: %d images, manifest in %s, logs in %s",
        len(records),
        plotter.manifest_path,
        log_file,
    )
