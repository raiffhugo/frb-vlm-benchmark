from __future__ import annotations

import argparse
import logging
from pathlib import Path

from evaluation.evaluator import EvaluationConfig, PredictionEvaluator
from simulate_dataset.cli import configure_logging


def add_evaluation_parser(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--predictions",
        type=Path,
        default=Path("results/predictions.jsonl"),
        help="JSONL file generated by the vlm_classifier module.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results"),
        help="Output directory for the metrics.",
    )
    parser.add_argument(
        "--task",
        default="multiclass",
        choices=("multiclass", "frb-binary"),
        help="Evaluation task: multiclass or FRB vs NON_FRB.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing metrics.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable verbose logging on the console and in the log file.",
    )


def run_evaluation(args: argparse.Namespace) -> None:
    project_root = Path.cwd().resolve()
    log_file = configure_logging(project_root, verbose=args.verbose)
    logging.getLogger("matplotlib").setLevel(logging.WARNING)

    config = EvaluationConfig(
        predictions_path=args.predictions.expanduser(),
        output_dir=args.output_dir.expanduser(),
        task=args.task,
    )
    evaluator = PredictionEvaluator(config=config, project_root=project_root)
    outputs = evaluator.evaluate(overwrite=args.overwrite)
    logging.getLogger(__name__).info(
        "Evaluation finished: metrics=%s, report=%s, confusion_matrix=%s, summary=%s, pdf=%s, logs=%s",
        outputs["metrics_json"],
        outputs["classification_report"],
        outputs["confusion_matrix_png"],
        outputs["summary_csv"],
        outputs["evaluation_report_pdf"],
        log_file,
    )
