from __future__ import annotations

import argparse
import logging
from pathlib import Path

from benchmark_export.converter import BenchmarkExportConfig, BenchmarkExporter
from simulate_dataset.cli import configure_logging


def add_benchmark_export_parser(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--labels",
        type=Path,
        default=Path("dataset/metadata/labels.jsonl"),
        help="labels.jsonl file generated by the simulation.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="Neutral directory to store the exported FITS files.",
    )
    parser.add_argument(
        "--manifest-jsonl",
        type=Path,
        default=None,
        help="Optional path for benchmark_manifest.jsonl.",
    )
    parser.add_argument(
        "--manifest-csv",
        type=Path,
        default=None,
        help="Optional path for benchmark_manifest.csv.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite generated sample_*.fits files and manifests.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable verbose logging.",
    )


def run_benchmark_export(args: argparse.Namespace) -> None:
    labels_path = args.labels.expanduser()
    project_root = labels_path.resolve().parents[2]
    log_file = configure_logging(project_root, verbose=args.verbose)

    exporter = BenchmarkExporter(
        config=BenchmarkExportConfig(
            labels_path=labels_path,
            output_dir=args.output_dir.expanduser(),
            manifest_jsonl=(
                args.manifest_jsonl.expanduser()
                if args.manifest_jsonl is not None
                else None
            ),
            manifest_csv=(
                args.manifest_csv.expanduser()
                if args.manifest_csv is not None
                else None
            ),
        ),
        project_root=project_root,
    )
    records = exporter.export(overwrite=args.overwrite)
    logging.getLogger(__name__).info(
        "Export finished: %d files, manifest in %s, logs in %s",
        len(records),
        exporter.manifest_jsonl,
        log_file,
    )
