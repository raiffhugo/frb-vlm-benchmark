from __future__ import annotations

import argparse
import logging
from pathlib import Path

from simulate_dataset.cli import configure_logging
from vlm_classifier.classifier import ClassifierConfig, VLMClassifier
from vlm_classifier.models import DryRunVLM, Gemma4VLM
from vlm_classifier.parser import classes_for_task, normalize_task


def add_vlm_classifier_parser(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("dataset/metadata/image_manifest.jsonl"),
        help="Image manifest generated by the plot_dataset module.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("results/predictions.jsonl"),
        help="JSONL predictions file.",
    )
    parser.add_argument(
        "--model",
        default="gemma4",
        choices=("gemma4",),
        help="Target VLM model.",
    )
    parser.add_argument(
        "--task",
        default="multiclass",
        choices=("multiclass", "frb-binary"),
        help="Classification task: multiclass or FRB vs NON_FRB.",
    )
    parser.add_argument(
        "--model-id",
        default=None,
        help="Hugging Face ID of the Gemma 4 model. Default: google/gemma-4-E4B-it.",
    )
    parser.add_argument(
        "--device-map",
        default="auto",
        help="device_map used in the Transformers from_pretrained call.",
    )
    parser.add_argument(
        "--dtype",
        default="auto",
        help='dtype used in from_pretrained. Use "none" to omit it.',
    )
    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=1024,
        help="Maximum number of tokens generated by the VLM.",
    )
    parser.add_argument(
        "--attn-implementation",
        default="sdpa",
        help='Transformers attention implementation. Use "none" to omit it.',
    )
    parser.add_argument(
        "--cache-implementation",
        default="static",
        help='cache_implementation used in generate. Use "none" to omit it.',
    )
    parser.add_argument(
        "--do-sample",
        action="store_true",
        help="Enable sampling. The default is deterministic greedy decoding.",
    )
    parser.add_argument(
        "--temperature",
        type=float,
        default=None,
        help="Temperature used only with --do-sample.",
    )
    parser.add_argument(
        "--top-p",
        type=float,
        default=None,
        help="Nucleus sampling used only with --do-sample.",
    )
    parser.add_argument(
        "--top-k",
        type=int,
        default=None,
        help="Top-k sampling used only with --do-sample.",
    )
    parser.add_argument(
        "--generation-seed",
        type=int,
        default=None,
        help="Transformers seed set before each generate call.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Generate reproducible random predictions without loading a real VLM.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Seed used by --dry-run mode.",
    )
    parser.add_argument(
        "--decision-threshold",
        type=float,
        default=0.5,
        help="Threshold on frb_probability to derive FRB in binary mode.",
    )
    parser.add_argument(
        "--max-retries",
        type=int,
        default=2,
        help="Number of retries per image on error.",
    )
    parser.add_argument(
        "--retry-delay",
        type=float,
        default=0.5,
        help="Wait in seconds between retries.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite results/predictions.jsonl if it exists.",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Enable verbose logging on the console and in the log file.",
    )


def run_vlm_classifier(args: argparse.Namespace) -> None:
    project_root = Path.cwd().resolve()
    log_file = configure_logging(project_root, verbose=args.verbose)
    task = normalize_task(args.task)

    if args.dry_run:
        model = DryRunVLM(seed=args.seed, labels=classes_for_task(task))
        logging.getLogger(__name__).info("Running vlm_classifier in dry-run mode.")
    else:
        model = Gemma4VLM(
            model_name=args.model_id or args.model,
            device_map=args.device_map,
            dtype=args.dtype,
            max_new_tokens=args.max_new_tokens,
            attn_implementation=args.attn_implementation,
            cache_implementation=args.cache_implementation,
            do_sample=args.do_sample,
            temperature=args.temperature,
            top_p=args.top_p,
            top_k=args.top_k,
            seed=args.generation_seed,
        )
        logging.getLogger(__name__).info("Running Gemma 4: %s", model.model_id)

    config = ClassifierConfig(
        manifest_path=args.manifest.expanduser(),
        output_path=args.output.expanduser(),
        max_retries=args.max_retries,
        retry_delay=args.retry_delay,
        task=task,
        decision_threshold=args.decision_threshold,
    )
    classifier = VLMClassifier(
        config=config,
        model=model,
        project_root=project_root,
    )
    predictions = classifier.run(overwrite=args.overwrite)
    logging.getLogger(__name__).info(
        "Classification finished: %d predictions, output in %s, logs in %s",
        len(predictions),
        classifier.output_path,
        log_file,
    )
